async function bytes(workbook: ExcelJS.Workbook): Promise<Uint8Array> {
  return new Uint8Array(await workbook.xlsx.writeBuffer({ useSharedStrings: true }));
}

function firstCompressedMember(zip: Buffer): number {
  for (let offset = 0; offset < zip.length - 46; offset++) {
    if (
      zip.readUInt32LE(offset) === 0x02014b50 &&
      zip.readUInt16LE(offset + 10) === 8 &&
      zip.readUInt32LE(offset + 24) > 1
    )
      return offset;
  }
  throw new Error("TEST fixture had no compressed member");
}

describe("Supercrew static report parsing", () => {
  it("uses detail rows once, keeps blank identifiers, and preserves independently rounded controls", async () => {
    const report = await parseSupercrewXlsx(await bytes(fixture()));
    expect(report.entries).toHaveLength(2);
    expect(report.entries[0]).toMatchObject({
      employeeId: null,
      jobCode: null,
      crew: "",
      timeEntryType: "",
      sourceRow: 13,
      laborCostCents: 0,
    });
    expect(report.reportedTotals).toEqual({
      hours: 0.32,
      travelHours: 0.22,
      laborCostCents: 1001,
      billableCostCents: 0,
    });
    expect(report.computedTotals).toEqual({
      hours: 0.3,
      travelHours: 0.2,
      laborCostCents: 1001,
      billableCostCents: 0,
    });
    expect(report.warnings).toEqual(
      expect.arrayContaining([
        expect.stringContaining("differs from the detail sum"),
        expect.stringContaining("provisional snapshot"),
        expect.stringContaining("Rates and costing policy remain unconfirmed"),
      ]),
    );
    expect(report.period).toEqual({ from: "2026-09-24", to: "2026-09-30" });
    expect(report.generatedAt).toBe("2026-09-29 2:53:33 PM");
    expect(report.formatVersion).toBe("supercrew-merged-job-report-v1");
  });

  it("keeps legitimate identical-looking intervals and produces deterministic occurrence identifiers", async () => {
    const original = await parseSupercrewXlsx(await bytes(fixture({ repeated: true })));
    const second = await parseSupercrewXlsx(await bytes(fixture({ repeated: true })));
    expect(original.entries).toHaveLength(3);
    expect(new Set(original.entries.map((entry) => entry.id)).size).toBe(3);
    expect(original.entries.map((entry) => entry.id)).toEqual(
      second.entries.map((entry) => entry.id),
    );
    expect(original.warnings).toContain(
      "Identical-looking records were retained with their original multiplicity for review.",
    );
  });

  it("accepts the narrower Timesheet header shape without inventing address or travel controls", async () => {
    const report = await parseSupercrewXlsx(await bytes(fixture({ timesheet: true })));
    expect(report.entries[0]).toMatchObject({ jobName: "TEST Job", jobAddress: "", role: "" });
    expect(report.reportedTotals.travelHours).toBeNull();
    expect(report.computedTotals.travelHours).toBe(0.2);
    expect(report.formatVersion).toBe("supercrew-timesheet-all-entries-v1");
    expect(report.warnings).toEqual(
      expect.arrayContaining([
        expect.stringContaining("independent travel control is not available"),
        expect.stringContaining("no address"),
      ]),
    );
  });

  it("rejects formulas even when they provide a plausible cached result", async () => {
    const workbook = fixture();
    (workbook.getWorksheet("All Entries") as ExcelJS.Worksheet).getCell("M13").value = {
      formula: "1/10",
      result: 0.1,
    };
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "unsupported cell value or formula",
    );
  });

  it("rejects an invalid or out-of-period work date", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("A13").value = "2026-09-31";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow("work date is invalid");
    details.getCell("A13").value = "2026-09-23";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "outside the selected period",
    );
  });

  it("requires structural headers and consistent report scopes", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("M12").value = "Estimated Hours";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "missing report columns",
    );
    details.getCell("M12").value = "Hours";
    const summary = workbook.getWorksheet("Overall Summary") as ExcelJS.Worksheet;
    summary.getCell("B6").value = "2026-09-01 to 2026-09-30";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow("disagree on dates");
  });

  it("rejects conflicting travel methods and blank hours instead of guessing", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("K14").value = "AutoClock";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "conflicting capture methods",
    );
    details.getCell("K14").value = "Travel Time";
    details.getCell("M13").value = "";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "expected a nonnegative number",
    );
  });

  it("preserves observed NoGPS work capture and edit annotations without treating it as travel", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("J13").value = "NoGPS";
    details.getCell("K13").value = "NoGPS";
    details.getCell("L13").value = "Edited";
    const report = await parseSupercrewXlsx(await bytes(workbook));
    expect(report.entries[0]).toMatchObject({
      kind: "work",
      clockInMethod: "NoGPS",
      clockOutMethod: "NoGPS",
      timeEntryType: "Edited",
      hours: 0.1,
      travel: false,
    });
    expect(report.warnings.some((warning) => warning.includes("NoGPS capture"))).toBe(true);
    details.getCell("K13").value = "Travel Time";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "conflicting capture methods",
    );
    details.getCell("K13").value = "Unpaid Break";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "conflicting capture methods",
    );
    details.getCell("K13").value = "TEST unknown method";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "unknown or conflicting capture methods",
    );
  });

  it("preserves the Overnight split work marker and synthetic source quantities", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    const summary = workbook.getWorksheet("Overall Summary") as ExcelJS.Worksheet;
    details.getCell("H13").value = "07:00";
    details.getCell("I13").value = "08:30";
    details.getCell("J13").value = "NoGPS";
    details.getCell("K13").value = "Overnight split";
    details.getCell("L13").value = "Edited";
    details.getCell("M13").value = 1.5;
    details.getCell("N13").value = 30.45;
    details.getCell("M16").value = 1.7;
    details.getCell("N16").value = 40.46;
    summary.getCell("H16").value = 1.7;
    summary.getCell("I16").value = 40.46;
    const report = await parseSupercrewXlsx(await bytes(workbook));
    expect(report.entries[0]).toMatchObject({
      kind: "work",
      clockIn: "07:00",
      clockOut: "08:30",
      clockInMethod: "NoGPS",
      clockOutMethod: "Overnight split",
      timeEntryType: "Edited",
      hours: 1.5,
      laborCostCents: 3045,
      billableCostCents: 0,
      travel: false,
      sourceRow: 13,
    });
    expect(report.entries).toHaveLength(2);
    expect(report.computedTotals).toEqual({
      hours: 1.7,
      travelHours: 0.2,
      laborCostCents: 4046,
      billableCostCents: 0,
    });
    expect(report.warnings.some((warning) => warning.includes("Overnight split capture"))).toBe(
      true,
    );
    expect(details.getCell("K13").value).toBe("Overnight split");
  });

  it.each(["Travel Time", "Unpaid Break", "TEST unknown method", "overnight split"])(
    "does not let Overnight split bypass the conflicting or unknown %s guard",
    async (method) => {
      const workbook = fixture();
      const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
      details.getCell("J13").value = "Overnight split";
      details.getCell("K13").value = method;
      await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
        "unknown or conflicting capture methods",
      );
    },
  );

  it("rejects missing footer and mismatched controls", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("M16").value = 1;
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "disagree on selected-period totals",
    );
    details.spliceRows(16, 1);
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "total footer is missing",
    );
  });

  it("bounds compressed files and worksheet rows before import", async () => {
    expect(() =>
      assertSafeSupercrewXlsx(new Uint8Array(SUPERCREW_XLSX_LIMITS.fileBytes + 1)),
    ).toThrow("10 MB");
    expect(() => assertSafeSupercrewXlsx(new Uint8Array([0, 1, 2]))).toThrow("unencrypted XLSX");
    const workbook = fixture();
    (workbook.getWorksheet("All Entries") as ExcelJS.Worksheet).getCell(
      SUPERCREW_XLSX_LIMITS.rowsPerSheet + 1,
      1,
    ).value = "TEST limit";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow("25,000 row limit");
  });

  it("rejects excessive expansion, forged member sizes, and encrypted ZIP members before workbook loading", async () => {
    const original = Buffer.from(await bytes(fixture()));
    const member = firstCompressedMember(original);
    const expanded = Buffer.from(original);
    expanded.writeUInt32LE(SUPERCREW_XLSX_LIMITS.expandedBytes + 1, member + 24);
    expect(() => assertSafeSupercrewXlsx(expanded)).toThrow("30 MB");
    const forged = Buffer.from(original);
    forged.writeUInt32LE(1, member + 24);
    expect(() => assertSafeSupercrewXlsx(forged)).toThrow("declared expansion limit");
    const encrypted = Buffer.from(original);
    encrypted.writeUInt16LE(encrypted.readUInt16LE(member + 8) | 1, member + 8);
    expect(() => assertSafeSupercrewXlsx(encrypted)).toThrow("Encrypted");
  });

  it("preserves signed unpaid-break adjustments and blank clocks without assigning them to a customer", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.spliceRows(15, 0, [
      "2026-09-24",
      "TEST Worker",
      "TEST Role",
      "",
      "",
      "Unpaid Break",
      "",
      "",
      "",
      "Unpaid Break",
      "Unpaid Break",
      "",
      -0.1,
      -1,
      0,
      "",
      "",
    ]);
    details.getCell("M17").value = 0.22;
    details.getCell("N17").value = 9.01;
    const summary = workbook.getWorksheet("Overall Summary") as ExcelJS.Worksheet;
    summary.getCell("H16").value = 0.22;
    summary.getCell("I16").value = 9.01;
    const report = await parseSupercrewXlsx(await bytes(workbook));
    expect(report.entries[2]).toMatchObject({
      kind: "unpaid_break",
      jobName: "Unpaid Break",
      jobAddress: "",
      clockIn: "",
      clockOut: "",
      hours: -0.1,
      laborCostCents: -100,
      travel: false,
    });
    expect(report.computedTotals).toMatchObject({
      hours: 0.2,
      travelHours: 0.2,
      laborCostCents: 901,
    });
    const groups = groupLaborEntries(report.entries);
    expect(groups.jobs.find((job) => job.name === "TEST Job")?.hours).toBe(0.3);
    expect(groups.jobs.find((job) => job.name === "Unpaid Break")?.hours).toBe(-0.1);
    expect(groups.workers[0]?.hours).toBe(0.2);
  });

  it("rejects a negative normal interval and a break labeled as a customer allocation", async () => {
    const workbook = fixture();
    const details = workbook.getWorksheet("All Entries") as ExcelJS.Worksheet;
    details.getCell("M13").value = -0.1;
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "expected a nonnegative number",
    );
    details.getCell("J13").value = "Unpaid Break";
    details.getCell("K13").value = "Unpaid Break";
    details.getCell("H13").value = "";
    details.getCell("I13").value = "";
    await expect(parseSupercrewXlsx(await bytes(workbook))).rejects.toThrow(
      "no job allocation was inferred",
    );
  });
});

interface PrivateTimesheetManifest {
  version: 1;
  report: Pick<
    LaborReport,
    | "period"
    | "generatedAt"
    | "formatVersion"
    | "filters"
    | "reportedTotals"
    | "computedTotals"
    | "reconciliationControls"
    | "warnings"
  >;
  entryCount: number;
  jobCount: number;
  workerCount: number;
  kindCounts: Record<LaborEntry["kind"], number>;
  blankIdentifierCounts: { employeeId: number; jobCode: number };
  entries: { index: number; expected: Partial<LaborEntry> }[];
}

// Both files stay private. See docs/supercrew-private-fixtures.md; never run with public CI logs.
for (const reference of [
  {
    label: "private source report reference",
    workbookEnv: "SUPERCREW_REFERENCE_XLSX",
    manifestEnv: "SUPERCREW_REFERENCE_MANIFEST",
  },
  {
    label: "private Timesheet reference",
    workbookEnv: "SUPERCREW_TIMESHEET_REFERENCE_XLSX",
    manifestEnv: "SUPERCREW_TIMESHEET_REFERENCE_MANIFEST",
  },
]) {
  const workbookPath = process.env[reference.workbookEnv];
  const manifestPath = process.env[reference.manifestEnv];
  describe.skipIf(!workbookPath || !manifestPath)(reference.label, () => {
    it("matches independently reviewed private controls and source records", async () => {
      const manifest: PrivateTimesheetManifest = JSON.parse(
        await readFile(manifestPath as string, "utf8"),
      );
      expect(manifest.version).toBe(1);
      const report = await parseSupercrewXlsx(await readFile(workbookPath as string));
      const grouped = groupLaborEntries(report.entries);
      const { entries, ...metadata } = report;
      expect(metadata).toEqual(manifest.report);
      expect(entries).toHaveLength(manifest.entryCount);
      expect(grouped.jobs).toHaveLength(manifest.jobCount);
      expect(grouped.workers).toHaveLength(manifest.workerCount);
      expect({
        work: entries.filter((entry) => entry.kind === "work").length,
        travel: entries.filter((entry) => entry.kind === "travel").length,
        unpaid_break: entries.filter((entry) => entry.kind === "unpaid_break").length,
      }).toEqual(manifest.kindCounts);
      expect({
        employeeId: entries.filter((entry) => entry.employeeId === null).length,
        jobCode: entries.filter((entry) => entry.jobCode === null).length,
      }).toEqual(manifest.blankIdentifierCounts);
      for (const check of manifest.entries) {
        expect(
          Number.isInteger(check.index) && check.index >= 0 && check.index < entries.length,
        ).toBe(true);
        expect(Object.keys(check.expected).length).toBeGreaterThan(0);
        expect(entries[check.index]).toMatchObject(check.expected);
      }
    });
  });
}
